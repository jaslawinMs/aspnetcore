namespace AutoPerf;

internal static class Characterization
{
    internal static async Task RunAsync()
    {
        using var timeout = new CancellationTokenSource(TimeSpan.FromMinutes(3));
        var minimal = AnalyzerScenario.GetPrepared("MinimalProgram").Definition;
        const string main = "System.Console.WriteLine(\"Hello\");\n";
        var extra = new[]
        {
            new ProfileDefinition("ExactlyTwoNodes", "Program", true, 1,
                "class Companion { }\npublic partial class Program { }\n", main, "Exactly two descendants in the analysed file."),
            new ProfileDefinition("TriviaOnly", "Program", false, 0,
                "/// <summary>Trivia is not another syntax node.</summary>\npublic partial class Program { }\n", main, "Structured trivia is not descended into."),
            new ProfileDefinition("WithAttribute", "Program", false, 0,
                "[System.Obsolete] public partial class Program { }\n", main, "Unchanged attribute guard."),
            new ProfileDefinition("WithMember", "Program", false, 0,
                "public partial class Program { public const int Value = 1; }\n", main, "Unchanged nonempty-member guard."),
            new ProfileDefinition("InNamespace", "Program", false, 0,
                "namespace Example { public partial class Program { } }\n", main, "Unchanged immediate-parent guard."),
            minimal with { Key = "Generated", Source = "// <auto-generated/>\n" + minimal.Source, ExpectedDiagnosticCount = 0 }
        };
        foreach (var definition in extra)
        {
            var scenario = new AnalyzerScenario(definition, definition.Key == "Generated" ? "Program.g.cs" : null);
            if (definition.Key == "ExactlyTwoNodes")
            {
                Evidence.Require(scenario.DescendantCount == 2, "The actual parser must reach the exact second-node boundary.");
            }
            if (definition.Key == "TriviaOnly")
            {
                Evidence.Require(scenario.DescendantCount == 1, "Structured trivia must not inflate DescendantNodes().");
            }
            await scenario.VerifyAsync("additional-semantic-contract", timeout.Token).ConfigureAwait(false);
        }
        foreach (var profile in new[] { "MinimalProgram", "LargeProgram", "LoneDeclaration", "EarlyGuard" })
        {
            var benchmark = new AnalyzerBenchmarks { Profile = profile };
            benchmark.Setup();
            var scenario = AnalyzerScenario.GetPrepared(profile);
            Evidence.Require(benchmark.Predicate() == scenario.Definition.ExpectedPredicate,
                "The actual BDN predicate method must return the expected result.");
            var diagnostics = scenario.Validate(await benchmark.AnalyzeCompilation().ConfigureAwait(false));
            var location = benchmark.UnchangedGetLocation();
            Evidence.Require(location.SourceTree == scenario.Declaration.SyntaxTree && location.SourceSpan == scenario.Declaration.Span,
                "The actual BDN control method must return the same source location.");
            Evidence.Write("actual-benchmark-method-contract", new
            {
                profile, actualMethodsExecuted = new[] { nameof(AnalyzerBenchmarks.Predicate), nameof(AnalyzerBenchmarks.AnalyzeCompilation), nameof(AnalyzerBenchmarks.UnchangedGetLocation) },
                actualPredicateResult = benchmark.Predicate(), actualDiagnosticResult = diagnostics,
                actualFreshDriverRan = true, actualTimingRunByThisCharacterization = false
            });
        }
    }
}
