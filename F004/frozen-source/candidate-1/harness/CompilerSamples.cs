using System.Collections.Immutable;
using System.Text;
using Microsoft.AspNetCore.Components;
using Microsoft.AspNetCore.Components.Analyzers;
using Microsoft.AspNetCore.Components.Rendering;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using Microsoft.CodeAnalysis.CSharp.Syntax;
using Microsoft.CodeAnalysis.Diagnostics;
using Microsoft.CodeAnalysis.Operations;

namespace AutoPerf;

public enum Shape
{
    NoLoops,
    OneIterator,
    Nested16,
    Nested64,
    NonRender,
    Promoted,
    Unmutated,
    Cached,
    SiblingSymbols
}

public enum Boundary
{
    WarmCompilation,
    FreshCompilation
}

internal sealed record ExpectedReference(int Start, int Length, string Name, bool Report);
internal sealed record DiagnosticRecord(string Id, string Severity, int Start, int Length, string Message);

internal sealed class CompilerSample
{
    private static readonly ImmutableArray<MetadataReference> References = CreateReferences();
    private readonly ImmutableArray<SyntaxTree> _trees;
    private readonly CSharpCompilationOptions _compilationOptions = new(OutputKind.DynamicallyLinkedLibrary,
        optimizationLevel: OptimizationLevel.Release, concurrentBuild: true, deterministic: true);
    private readonly ImmutableArray<DiagnosticAnalyzer> _analyzers = [new ForLoopIteratorInClosureAnalyzer()];
    private readonly CompilationWithAnalyzersOptions _driverOptions;
    private readonly List<ExpectedReference> _references = [];
    private readonly string _source;
    private readonly int _expectedLoops;
    private readonly int _expectedCallbacks;
    private readonly bool _adjacentArray;

    public string Label { get; }
    public CSharpCompilation Compilation { get; }

    public CompilerSample(Shape shape, bool concurrent = false, bool generated = false, bool adjacentArray = false)
    {
        _adjacentArray = adjacentArray;
        Label = $"{shape}-{(concurrent ? "concurrent" : "serial")}-{(generated ? "generated" : "ordinary")}{(adjacentArray ? "-adjacent-array" : "")}";
        _driverOptions = new CompilationWithAnalyzersOptions(new AnalyzerOptions([]), onAnalyzerException: null,
            concurrentAnalysis: concurrent, logAnalyzerExecutionTime: false, reportSuppressedDiagnostics: false);
        var source = new StringBuilder();
        if (generated)
        {
            source.AppendLine("// <auto-generated/>");
        }
        source.AppendLine("using System;");
        source.AppendLine("using Microsoft.AspNetCore.Components;");
        source.AppendLine("using Microsoft.AspNetCore.Components.Rendering;");
        source.AppendLine("namespace AutoPerfInput;");
        source.AppendLine("public sealed class Sample : ComponentBase");
        source.AppendLine("{");
        source.AppendLine("    private static void Use(params int[] values) { }");
        source.AppendLine("    protected override void BuildRenderTree(RenderTreeBuilder builder)");
        source.AppendLine("    {");
        if (adjacentArray)
        {
            source.AppendLine("        for (int i = 0; i < 3; i++) { }");
            source.AppendLine("        builder.AddAttribute(0, \"value\", new int[] { 1, 2 });");
            _expectedLoops = 1;
        }
        else if (shape is Shape.Nested16 or Shape.Nested64 or Shape.OneIterator)
        {
            var depth = shape switch { Shape.Nested16 => 16, Shape.Nested64 => 64, _ => 1 };
            var callbacks = shape switch { Shape.Nested16 => 16, Shape.Nested64 => 32, _ => 1 };
            for (var index = 0; index < depth; index++)
            {
                source.AppendLine($"        for (int i{index} = 0; i{index} < 3; i{index}++)");
                source.AppendLine("        {");
            }
            for (var callback = 0; callback < callbacks; callback++)
            {
                AddCallback(Enumerable.Range(0, depth).Select(index => "i" + index), report: true);
            }
            for (var index = 0; index < depth; index++)
            {
                source.AppendLine("        }");
            }
            _expectedLoops = depth;
            _expectedCallbacks = callbacks;
        }
        else if (shape is Shape.Promoted or Shape.Unmutated or Shape.Cached or Shape.SiblingSymbols)
        {
            var loops = shape == Shape.SiblingSymbols ? 2 : 1;
            for (var index = 0; index < loops; index++)
            {
                var atBottom = shape is Shape.Promoted or Shape.Unmutated ? "" : "i++";
                source.AppendLine($"        for (int i = 0; i < 3; {atBottom})");
                source.AppendLine("        {");
                if (shape == Shape.Cached)
                {
                    source.AppendLine("            var copy = i;");
                }
                AddCallback([shape == Shape.Cached ? "copy" : "i"], report: shape is not Shape.Cached and not Shape.Unmutated);
                if (shape == Shape.Promoted)
                {
                    source.AppendLine("            i++;");
                }
                else if (shape == Shape.Unmutated)
                {
                    source.AppendLine("            break;");
                }
                source.AppendLine("        }");
            }
            _expectedLoops = loops;
            _expectedCallbacks = loops;
        }
        else
        {
            source.AppendLine("        builder.AddContent(0, \"no loop\");");
        }
        source.AppendLine("    }");
        if (shape == Shape.NonRender && !adjacentArray)
        {
            for (var index = 0; index < 64; index++)
            {
                source.AppendLine($"    private void Other{index}(RenderTreeBuilder builder)");
                source.AppendLine("    {");
                source.AppendLine("        for (int i = 0; i < 3; i++)");
                source.AppendLine("        {");
                AddCallback(["i"], report: false);
                source.AppendLine("        }");
                source.AppendLine("    }");
            }
            _expectedLoops = 64;
            _expectedCallbacks = 64;
        }
        source.AppendLine("}");
        _source = source.ToString();
        _trees = [CSharpSyntaxTree.ParseText(Microsoft.CodeAnalysis.Text.SourceText.From(_source, Encoding.UTF8),
            new CSharpParseOptions(LanguageVersion.CSharp13), generated ? "Sample.g.cs" : "Sample.cs")];
        Compilation = CreateCompilation();
        ValidateProducer();

        void AddCallback(IEnumerable<string> names, bool report)
        {
            source.Append("        builder.AddAttribute(0, \"onclick\", EventCallback.Factory.Create<int>(this, () => Use(");
            var first = true;
            foreach (var name in names)
            {
                if (!first)
                {
                    source.Append(", ");
                }
                first = false;
                _references.Add(new ExpectedReference(source.Length, name.Length, name, report));
                source.Append(name);
            }
            source.AppendLine(")));");
        }
    }

    public CSharpCompilation CreateCompilation() => CSharpCompilation.Create("AutoPerfF004Input", _trees, References, _compilationOptions);

    public async Task<ImmutableArray<Diagnostic>> AnalyzeAsync(Boundary boundary)
    {
        var compilation = boundary == Boundary.FreshCompilation ? CreateCompilation() : Compilation;

        return await compilation.WithAnalyzers(_analyzers, _driverOptions).GetAnalyzerDiagnosticsAsync();
    }

    public IReadOnlyList<DiagnosticRecord> Validate(ImmutableArray<Diagnostic> diagnostics, bool currentDefaultClass = false)
    {
        var actual = diagnostics.Select(diagnostic => new DiagnosticRecord(diagnostic.Id, diagnostic.Severity.ToString(),
            diagnostic.Location.SourceSpan.Start, diagnostic.Location.SourceSpan.Length, diagnostic.GetMessage()))
            .OrderBy(record => record.Start).ThenBy(record => record.Length).ToArray();
        if (_adjacentArray)
        {
            Evidence.Require(currentDefaultClass ? actual.Length == 0 : actual.Length == 1 && actual[0].Id == "AD0001",
                "The explicitly pre-existing adjacent array/null-namespace boundary changed unexpectedly:" + Evidence.Compact(actual));
        }
        else
        {
            var expected = _references.Where(reference => reference.Report).Select(reference => new DiagnosticRecord(
                "BL0014", nameof(DiagnosticSeverity.Warning), reference.Start, reference.Length,
                $"For loop iterator '{reference.Name}' is used in a closure or RenderFragment/ChildContent. This can lead to unexpected runtime behavior."))
                .OrderBy(record => record.Start).ThenBy(record => record.Length).ToArray();
            Evidence.Require(actual.SequenceEqual(expected), $"{Label}:wrong full-owner diagnostics.\nExpected:{Evidence.Compact(expected)}\nActual:{Evidence.Compact(actual)}");
        }

        return actual;
    }

    public void WriteInputProof()
    {
        var directory = Path.Combine(Evidence.InputDirectory, Label);
        Directory.CreateDirectory(directory);
        var file = Path.Combine(directory, _trees[0].FilePath);
        File.WriteAllText(file, _source, new UTF8Encoding(encoderShouldEmitUTF8Identifier: false));
        Evidence.Write("producer-" + Label, new
        {
            Label, expectedLoops = _expectedLoops, expectedCallbacks = _expectedCallbacks, expectedReferences = _references,
            expectedBL0014 = _references.Count(reference => reference.Report), inputSha256 = Evidence.Hash(file),
            validCompilerInput = true, actualFrameworkMetadata = typeof(ComponentBase).Assembly.Location,
            language = nameof(LanguageVersion.CSharp13), adjacentPreExistingArrayBoundary = _adjacentArray
        });
    }

    private void ValidateProducer()
    {
        var errors = Compilation.GetDiagnostics().Where(diagnostic => diagnostic.Severity == DiagnosticSeverity.Error).ToArray();
        Evidence.Require(errors.Length == 0, "Invalid compiler sample:" + Evidence.Compact(errors.Select(error => error.ToString())));
        var component = Compilation.GetTypeByMetadataName(typeof(ComponentBase).FullName!)
            ?? throw new InvalidOperationException("Actual ComponentBase metadata missing.");
        var builder = Compilation.GetTypeByMetadataName(typeof(RenderTreeBuilder).FullName!)
            ?? throw new InvalidOperationException("Actual RenderTreeBuilder metadata missing.");
        var factory = Compilation.GetTypeByMetadataName(typeof(EventCallbackFactory).FullName!)
            ?? throw new InvalidOperationException("Actual EventCallbackFactory metadata missing.");
        var type = Compilation.GetTypeByMetadataName("AutoPerfInput.Sample") ?? throw new InvalidOperationException("Sample type missing.");
        Evidence.Require(SymbolEqualityComparer.Default.Equals(type.BaseType, component), "Sample is not a real ComponentBase subclass.");
        var render = type.GetMembers("BuildRenderTree").OfType<IMethodSymbol>().Single();
        Evidence.Require(render.IsOverride && SymbolEqualityComparer.Default.Equals(render.OverriddenMethod?.ContainingType, component),
            "Sample is not the actual BuildRenderTree override.");
        var tree = _trees[0];
        var model = Compilation.GetSemanticModel(tree);
        var root = tree.GetRoot();
        var locals = root.DescendantNodes().OfType<ForStatementSyntax>().SelectMany(loop => loop.Declaration!.Variables)
            .Select(variable => model.GetDeclaredSymbol(variable) as ILocalSymbol ?? throw new InvalidOperationException("Missing real iterator symbol.")).ToArray();
        Evidence.Require(locals.Length == _expectedLoops && locals.Distinct(SymbolEqualityComparer.Default).Count() == _expectedLoops,
            "Actual distinct compiler-owned loop symbols disagree with the input shape.");
        var factories = root.DescendantNodes().OfType<InvocationExpressionSyntax>()
            .Select(invocation => model.GetOperation(invocation)).OfType<IInvocationOperation>()
            .Where(operation => SymbolEqualityComparer.Default.Equals(operation.TargetMethod.ContainingType, factory)).ToArray();
        Evidence.Require(factories.Length == _expectedCallbacks, "Actual bound factory invocation count differs.");
        foreach (var operation in root.DescendantNodes().OfType<InvocationExpressionSyntax>()
            .Select(invocation => model.GetOperation(invocation)).OfType<IInvocationOperation>()
            .Where(operation => operation.TargetMethod.Name == "AddAttribute" && !_adjacentArray))
        {
            Evidence.Require(SymbolEqualityComparer.Default.Equals(operation.Instance?.Type, builder)
                && operation.Arguments.Length == 3 && operation.Arguments[2].Value is IInvocationOperation value
                && SymbolEqualityComparer.Default.Equals(value.TargetMethod.ContainingType, factory),
                "Attribute does not reach the actual analyzer's event-callback branch.");
        }
        foreach (var reference in _references)
        {
            var node = root.FindNode(new Microsoft.CodeAnalysis.Text.TextSpan(reference.Start, reference.Length), getInnermostNodeForTie: true);
            Evidence.Require(model.GetOperation(node) is ILocalReferenceOperation local && local.Local.Name == reference.Name,
                "Expected captured occurrence is not the real compiler-owned local reference.");
        }
    }

    private static ImmutableArray<MetadataReference> CreateReferences()
    {
        var tpa = AppContext.GetData("TRUSTED_PLATFORM_ASSEMBLIES") as string
            ?? throw new InvalidOperationException("Actual runtime metadata list missing.");

        return tpa.Split(Path.PathSeparator).Append(typeof(ComponentBase).Assembly.Location).Distinct(StringComparer.OrdinalIgnoreCase)
            .Select(file => MetadataReference.CreateFromFile(file)).ToImmutableArray<MetadataReference>();
    }
}
