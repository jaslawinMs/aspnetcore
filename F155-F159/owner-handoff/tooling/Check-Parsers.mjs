import fs from 'node:fs';
import path from 'node:path';
import assert from 'node:assert/strict';
import { fileURLToPath } from 'node:url';
import { parsePe, parsePdb, parseXml, hash } from './evidence.mjs';
const root = path.dirname(fileURLToPath(import.meta.url));
const pe = parsePe(fs.readFileSync(path.join(root, 'identity', 'bin', 'Release', 'net12.0', 'Identity.dll')));
const pdb = parsePdb(fs.readFileSync(path.join(root, 'identity', 'bin', 'Release', 'net12.0', 'Identity.pdb')));
assert.equal(pe.codeView[0].guid, pdb.guid);
assert.equal(pe.codeView[0].stamp, pdb.stamp);
const source = fs.readFileSync(path.join(root, 'identity', 'StartupHook.cs'));
const document = pdb.documents.find(d => d.name.endsWith('StartupHook.cs'));
assert.equal(document.checksum, hash(source));
const xml = parseXml('<?xml version="1.0"?><a x="a&amp;&quot;"><b><![CDATA[<raw>]]></b><!-- c --><c>&#65;&#x42;</c></a>');
assert.equal(xml.attributes.x, 'a&"');
assert.equal(xml.children[0].text, '<raw>');
assert.equal(xml.children[1].text, 'AB');
assert.throws(() => parseXml('<a></b>'));
console.log(JSON.stringify({ parserSelfCheck: 'passed', pe, pdbDocument: document, xmlCases: 4 }, null, 2));
